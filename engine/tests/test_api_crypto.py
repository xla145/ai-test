import base64
import json
import importlib.util

import httpx
import pytest
from cryptography.hazmat.primitives import serialization, padding
from cryptography.hazmat.primitives.asymmetric import rsa, padding as rsa_padding
from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes

from aitest.api_crypto import prepare, response_body
from aitest.api_runtime import auth_resolver, execute_case


@pytest.fixture
def protocol(tmp_path):
    private = rsa.generate_private_key(public_exponent=65537, key_size=2048)
    pub, priv = tmp_path / 'public.pem', tmp_path / 'private.pem'
    pub.write_bytes(private.public_key().public_bytes(serialization.Encoding.PEM, serialization.PublicFormat.SubjectPublicKeyInfo))
    priv.write_bytes(private.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8, serialization.NoEncryption()))
    return {'api_crypto': {'protocol': 'ruoyi', 'public_key_file': str(pub), 'private_key_file': str(priv), 'headers': {'clientid': 'test-client'}}}, private


def encrypted_response(private):
    # Fixed vector generated by the target project's CryptoJS implementation.
    key = b'0123456789abcdef0123456789abcdef'
    wrapped = private.public_key().encrypt(base64.b64encode(key), rsa_padding.PKCS1v15())
    return httpx.Response(200, headers={'encrypt-key': base64.b64encode(wrapped).decode()},
                          text='2maKJMGztYtT98OmMady/XlN71dO/qveLYpk27CLR9BaiUm/+ofXk3XRJTxpNZs7Ka0BiaTJjIy/nByDxfSugQ==')


def test_cryptojs_response_vector_and_request_envelope(protocol):
    env, private = protocol
    response = encrypted_response(private)
    assert response_body(env, response)['data']['access_token'] == '测试-token'
    wire = prepare(env, {'method': 'POST', 'encrypt': True}, {'json': {'password': '秘密'}, 'headers': {}})
    assert 'json' not in wire and wire['headers']['clientid'] == 'test-client'
    key = base64.b64decode(private.decrypt(base64.b64decode(wire['headers']['encrypt-key']), rsa_padding.PKCS1v15()))
    assert len(key) == 32
    decryptor = Cipher(algorithms.AES(key), modes.ECB()).decryptor()
    padded = decryptor.update(base64.b64decode(wire['content'])) + decryptor.finalize()
    unpad = padding.PKCS7(128).unpadder()
    assert json.loads(unpad.update(padded) + unpad.finalize()) == {'password': '秘密'}
    assert prepare(env, {'method': 'POST', 'encrypt': True}, {'json': {}, 'headers': {}})['headers']['encrypt-key'] != wire['headers']['encrypt-key']


def test_login_cache_flow_assertions_and_redaction(protocol):
    env, private = protocol
    calls = []
    def handle(req):
        calls.append(req)
        assert req.headers['clientid'] == 'test-client'
        if req.url.path == '/login':
            assert req.headers['encrypt-key'] and b'password' not in req.content
        return encrypted_response(private)
    with httpx.Client(base_url='https://example.test', transport=httpx.MockTransport(handle)) as client:
        auth = auth_resolver(client, env, {'method': 'POST', 'path': '/login', 'encrypt': True, 'token_path': 'data.access_token'}, [{'role': 'admin', 'username': 'test', 'password': 'secret'}])
        assert auth('admin') == auth('admin') == 'Bearer 测试-token'
        result = execute_case({'steps': [{'method': 'POST', 'path': '/test', 'encrypt': True, 'body': {}, 'auth': False, 'expected_fields': {'code': 200}, 'extract': {'token': 'data.access_token'}}]}, client, env, {}, auth)
    assert len(calls) == 2 and result['status'] == 'passed'
    assert '测试-token' not in json.dumps(result, ensure_ascii=False)
    assert result['steps'][0]['response']['headers']['encrypt-key'] == '[已隐藏]'


def test_plain_requests_and_fail_closed(protocol):
    env, private = protocol
    assert prepare({}, {}, {'json': {'plain': True}})['json'] == {'plain': True}
    assert response_body(env, httpx.Response(200, json={'ok': True})) == {'ok': True}
    with pytest.raises(ValueError, match='先配置'):
        prepare({}, {'encrypt': True}, {'json': {}})
    with pytest.raises(ValueError, match='POST / PUT'):
        prepare(env, {'encrypt': True, 'method': 'GET'}, {'json': {}})
    with pytest.raises(ValueError, match='响应解密失败'):
        response_body(env, httpx.Response(200, headers={'encrypt-key': 'broken'}, text='broken'))


def test_export_preserves_encryption_and_carries_runtime(tmp_path, protocol, monkeypatch):
    from aitest.apigen import write_pytest_suite
    from aitest.models import TestCase, ApiSpec
    from aitest.runner import EnvConfig
    env, private = protocol
    case = TestCase(title='加密接口', execution_mode='api', api=ApiSpec(method='POST', path='/login', body={}, encrypt=True))
    out = tmp_path / 'suite'
    write_pytest_suite([case], out)
    assert json.loads((out / 'data/api.json').read_text())[0]['encrypt'] is True
    assert json.loads(EnvConfig(base_url='https://test', api_crypto=env['api_crypto']).to_env()['AITEST_API_CRYPTO']) == env['api_crypto']
    spec = importlib.util.spec_from_file_location('exported_crypto', out / '_aitest_crypto.py')
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    assert module.response_body(env, encrypted_response(private))['code'] == 200


def test_environment_token_and_clientid_reach_the_wire_and_request_trace():
    def handle(request):
        valid = (request.headers.get('Authorization') == 'Bearer browser-token'
                 and request.headers.get('clientid') == 'web-client')
        return httpx.Response(200, json={'code': 200 if valid else 401})

    case = {'steps': [{'method': 'GET', 'path': '/profile', 'auth': True,
                       'expected_fields': {'code': 200}}]}
    env = {'auth_token': 'Bearer browser-token', 'auth_header': 'Authorization'}
    with httpx.Client(base_url='https://test', transport=httpx.MockTransport(handle)) as client:
        assert execute_case(case, client, env, {}, lambda _: '')['status'] == 'failed'
        env['api_crypto'] = {'headers': {'clientid': 'web-client'}}
        result = execute_case(case, client, env, {}, lambda _: '')
    assert result['status'] == 'passed'
    assert result['steps'][0]['request']['headers']['clientid'] == 'web-client'
    assert result['steps'][0]['request']['headers']['Authorization'] == '[已隐藏]'
    assert 'browser-token' not in json.dumps(result)
